-- Perfis de acesso usados pelo Spring Security
CREATE TABLE funcao (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(30) NOT NULL UNIQUE
);

-- Credenciais de login; "ativo" faz a exclusão lógica e "bloqueado" impede o acesso
CREATE TABLE usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(120) NOT NULL UNIQUE,
    senha      VARCHAR(100) NOT NULL,
    ativo      BOOLEAN NOT NULL DEFAULT TRUE,
    bloqueado  BOOLEAN NOT NULL DEFAULT FALSE,
    funcao_id  BIGINT NOT NULL REFERENCES funcao(id),
    criado_em  TIMESTAMP NOT NULL DEFAULT now()
);

-- Proprietários dos veículos
CREATE TABLE cliente (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome     VARCHAR(120) NOT NULL,
    cpf      VARCHAR(14)  NOT NULL UNIQUE,
    telefone VARCHAR(20),
    email    VARCHAR(120),
    endereco VARCHAR(255)
);

-- Equipe da oficina; o salário alimenta o gasto com salários do dashboard
CREATE TABLE funcionario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(120) NOT NULL,
    cpf        VARCHAR(14)  NOT NULL UNIQUE,
    telefone   VARCHAR(20),
    email      VARCHAR(120),
    cargo      VARCHAR(60),
    salario    NUMERIC(10,2) NOT NULL CHECK (salario >= 0),
    status     VARCHAR(10) NOT NULL DEFAULT 'ATIVO' CHECK (status IN ('ATIVO','INATIVO')),
    usuario_id BIGINT UNIQUE REFERENCES usuario(id)
);

-- Veículos atendidos; o status acompanha o andamento do reparo
CREATE TABLE veiculo (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marca            VARCHAR(50) NOT NULL,
    modelo           VARCHAR(60) NOT NULL,
    ano              INT CHECK (ano BETWEEN 1900 AND 2100),
    cor              VARCHAR(30),
    placa            VARCHAR(8) NOT NULL UNIQUE,
    quilometragem    INT CHECK (quilometragem >= 0),
    data_entrada     TIMESTAMP NOT NULL DEFAULT now(),
    previsao_entrega TIMESTAMP,
    data_entrega     TIMESTAMP,
    status           VARCHAR(20) NOT NULL DEFAULT 'AGUARDANDO_ANALISE'
        CHECK (status IN ('AGUARDANDO_ANALISE','AGUARDANDO_PECAS','EM_MANUTENCAO',
                          'TESTES_FINAIS','CONCLUIDO','ENTREGUE')),
    cliente_id       BIGINT NOT NULL REFERENCES cliente(id)
);

-- Catálogo e saldo do estoque; valor_unitario é o preço de venda
CREATE TABLE peca (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(120) NOT NULL,
    fabricante     VARCHAR(80),
    quantidade     INT NOT NULL DEFAULT 0 CHECK (quantidade >= 0),
    valor_unitario NUMERIC(10,2) NOT NULL CHECK (valor_unitario >= 0),
    estoque_minimo INT NOT NULL DEFAULT 0 CHECK (estoque_minimo >= 0)
);

-- Módulo principal; valor_pecas e valor_total são calculados por triggers
CREATE TABLE ordem_servico (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero         VARCHAR(20) NOT NULL UNIQUE,
    veiculo_id     BIGINT NOT NULL REFERENCES veiculo(id),
    funcionario_id BIGINT REFERENCES funcionario(id),
    problema       TEXT NOT NULL,
    diagnostico    TEXT,
    valor_mao_obra NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (valor_mao_obra >= 0),
    valor_pecas    NUMERIC(10,2) NOT NULL DEFAULT 0,
    valor_total    NUMERIC(10,2) NOT NULL DEFAULT 0,
    status         VARCHAR(20) NOT NULL DEFAULT 'ABERTA'
        CHECK (status IN ('ABERTA','EM_ANDAMENTO','AGUARDANDO_PECAS','CONCLUIDA','CANCELADA')),
    data_abertura  TIMESTAMP NOT NULL DEFAULT now(),
    data_conclusao TIMESTAMP
);

-- Resolve a relação N:N entre OS e peça, guardando o preço cobrado na época
CREATE TABLE item_os (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    os_id          BIGINT NOT NULL REFERENCES ordem_servico(id) ON DELETE CASCADE,
    peca_id        BIGINT NOT NULL REFERENCES peca(id),
    quantidade     INT NOT NULL CHECK (quantidade > 0),
    valor_unitario NUMERIC(10,2) NOT NULL CHECK (valor_unitario >= 0)
);

-- Histórico de entradas e saídas; custo_unitario das entradas alimenta o gasto com peças
CREATE TABLE movimentacao_estoque (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    peca_id        BIGINT NOT NULL REFERENCES peca(id),
    tipo           VARCHAR(10) NOT NULL CHECK (tipo IN ('ENTRADA','SAIDA')),
    quantidade     INT NOT NULL CHECK (quantidade > 0),
    custo_unitario NUMERIC(10,2),
    os_id          BIGINT REFERENCES ordem_servico(id),
    observacao     VARCHAR(255),
    data           TIMESTAMP NOT NULL DEFAULT now()
);

-- Pedidos de compra feitos pelos funcionários e decididos pelo gerente
CREATE TABLE solicitacao_peca (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    funcionario_id BIGINT NOT NULL REFERENCES funcionario(id),
    peca_id        BIGINT NOT NULL REFERENCES peca(id),
    quantidade     INT NOT NULL CHECK (quantidade > 0),
    justificativa  VARCHAR(255),
    status         VARCHAR(10) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status IN ('PENDENTE','APROVADA','COMPRADA','RECUSADA')),
    data           TIMESTAMP NOT NULL DEFAULT now()
);

-- Alertas exibidos para cada usuário
CREATE TABLE notificacao (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    tipo       VARCHAR(30) NOT NULL
        CHECK (tipo IN ('ESTOQUE_BAIXO','OS_ATRASADA','SOLICITACAO_PENDENTE',
                        'VEICULO_AGUARDANDO_PECA','SERVICO_CONCLUIDO')),
    mensagem   VARCHAR(255) NOT NULL,
    lida       BOOLEAN NOT NULL DEFAULT FALSE,
    data       TIMESTAMP NOT NULL DEFAULT now()
);

-- Histórico cronológico de cada veículo
CREATE TABLE timeline_veiculo (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veiculo_id BIGINT NOT NULL REFERENCES veiculo(id) ON DELETE CASCADE,
    evento     VARCHAR(30) NOT NULL
        CHECK (evento IN ('ENTRADA','DIAGNOSTICO','SOLICITACAO_PECA','APROVACAO_PECA',
                          'INICIO_CONSERTO','MUDANCA_STATUS','CONCLUSAO','ENTREGA')),
    descricao  VARCHAR(255),
    usuario_id BIGINT REFERENCES usuario(id),
    data       TIMESTAMP NOT NULL DEFAULT now()
);

-- Registro de ações críticas, consultado pelo Admin Master
CREATE TABLE auditoria (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT REFERENCES usuario(id),
    acao        VARCHAR(30) NOT NULL,
    entidade    VARCHAR(50) NOT NULL,
    entidade_id BIGINT,
    detalhes    TEXT,
    data        TIMESTAMP NOT NULL DEFAULT now()
);

-- Benefícios e outras despesas, usados no cálculo do lucro do dashboard
CREATE TABLE despesa (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo      VARCHAR(20) NOT NULL CHECK (tipo IN ('BENEFICIO','OUTRAS')),
    descricao VARCHAR(120),
    valor     NUMERIC(10,2) NOT NULL CHECK (valor >= 0),
    data      DATE NOT NULL DEFAULT current_date
);
